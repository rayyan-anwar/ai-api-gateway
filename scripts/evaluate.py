"""Evaluate gateway behaviour in-process and save genuine results to results/.

Measures core-pipeline latency/throughput (no web framework, no network), rate-limiter accuracy, fallback
success, timeout enforcement, and a small sentiment sanity check of the built-in local provider.

Usage: python scripts/evaluate.py     Author: Rayyan Anwar
"""
import asyncio
import json
import platform
import statistics
import sys
import time
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import local_nlp  # noqa: E402
from app.config import Settings, Target  # noqa: E402
from app.errors import GatewayError  # noqa: E402
from app.gateway import Gateway  # noqa: E402
from app.providers import LocalProvider  # noqa: E402
from app.ratelimit import TokenBucketLimiter  # noqa: E402
from app.simulated import FailingProvider, SlowProvider  # noqa: E402


def pct(vals, p):
    s = sorted(vals)
    return s[min(len(s) - 1, round(p / 100 * (len(s) - 1)))]


class Clock:
    t = 0.0

    def __call__(self):
        return self.t


def load_requests():
    return [json.loads(line) for line in (ROOT / "data" / "sample_requests.jsonl").read_text().splitlines()]


async def latency_and_throughput(reqs):
    gw = Gateway(Settings(), {"local": LocalProvider()})
    n, lat = 300, []
    for i in range(n):
        t0 = time.perf_counter()
        await gw.chat(reqs[i % len(reqs)])
        lat.append((time.perf_counter() - t0) * 1e3)
    t0 = time.perf_counter()
    total = 400
    for start in range(0, total, 50):
        await asyncio.gather(*[gw.chat(reqs[(start + j) % len(reqs)]) for j in range(50)])
    wall = time.perf_counter() - t0
    return {"sequential_requests": n, "latency_ms": {"p50": pct(lat, 50), "p95": pct(lat, 95), "p99": pct(lat, 99),
                                                       "mean": statistics.mean(lat)},
            "concurrent_requests": total, "concurrency": 50, "requests_per_s": total / wall}


def rate_limit_accuracy():
    clk = Clock()
    rl = TokenBucketLimiter(rate_per_min=60, burst=10, clock=clk)
    first = sum(rl.check("c").allowed for _ in range(30))
    clk.t += 5.0
    later = sum(rl.check("c").allowed for _ in range(10))
    return {"burst": 10, "rate_per_min": 60, "immediate_30_allowed": first, "immediate_expected": 10,
            "after_5s_10_attempts_allowed": later, "after_5s_expected": 5,
            "exact_match": first == 10 and later == 5}


async def fallback_success(reqs):
    routes = {"x": (Target("failing", "m"), Target("local", "local/summarizer"))}
    failing = FailingProvider(503)
    gw = Gateway(Settings(routes=routes), {"failing": failing, "local": LocalProvider()})
    ok = used = 0
    for i in range(100):
        r = await gw.chat({"model": "x", "messages": reqs[i % len(reqs)]["messages"]})
        ok += 1
        used += r["fallback_used"]
    return {"requests": 100, "succeeded": ok, "fallback_used": used, "primary_calls": failing.calls}


async def timeout_enforcement():
    gw = Gateway(Settings(routes={"x": (Target("slow", "m"),)}, request_timeout_s=0.1), {"slow": SlowProvider(2.0)})
    t0 = time.perf_counter()
    status = None
    try:
        await gw.chat({"model": "x", "messages": [{"role": "user", "content": "hello"}]})
    except GatewayError as exc:
        status = exc.status
    return {"configured_timeout_s": 0.1, "provider_delay_s": 2.0, "status": status,
            "elapsed_s": time.perf_counter() - t0}


def sentiment_sanity():
    rows = [json.loads(line) for line in (ROOT / "data" / "sentiment_sanity.jsonl").read_text().splitlines()]
    wrong, conf = [], {}
    for r in rows:
        pred = local_nlp.sentiment(r["text"])["label"]
        conf[f"{r['label']}->{pred}"] = conf.get(f"{r['label']}->{pred}", 0) + 1
        if pred != r["label"]:
            wrong.append({"text": r["text"], "expected": r["label"], "predicted": pred})
    return {"n": len(rows), "accuracy": 1 - len(wrong) / len(rows), "confusion": conf, "errors": wrong,
            "caveat": "28 author-written sentences; sanity check only, not a benchmark."}


def to_md(res):
    e, lt, rl, fb, to, se = (res["environment"], res["latency_throughput"], res["rate_limiter"], res["fallback"],
                             res["timeout"], res["sentiment_sanity"])
    lat = lt["latency_ms"]
    lines = [
        "# Results (generated by `scripts/evaluate.py`)", "",
        f"- Created (UTC): {res['created_utc']}",
        f"- Machine: {e['platform']}; Python {e['python']}; CPUs: {e['cpu_count']}",
        "- Scope: in-process gateway core with the built-in local provider. No web framework, no network, no real vendor APIs.", "",
        "## Latency and throughput (local provider)", "",
        "| Metric | Value |", "|---|---:|",
        f"| Sequential requests | {lt['sequential_requests']} |",
        f"| Latency p50 / p95 / p99 (ms) | {lat['p50']:.3f} / {lat['p95']:.3f} / {lat['p99']:.3f} |",
        f"| Mean latency (ms) | {lat['mean']:.3f} |",
        f"| Throughput at concurrency {lt['concurrency']} (req/s) | {lt['requests_per_s']:.0f} |", "",
        "## Behavioural checks", "",
        "| Check | Observed | Expected |", "|---|---|---|",
        f"| Rate limiter, 30 immediate requests (burst 10) | {rl['immediate_30_allowed']} allowed | {rl['immediate_expected']} |",
        f"| Rate limiter, 10 attempts after 5 s (60/min) | {rl['after_5s_10_attempts_allowed']} allowed | {rl['after_5s_expected']} |",
        f"| Fallback with failing primary, 100 requests | {fb['succeeded']} succeeded, {fb['fallback_used']} via fallback | 100 / 100 |",
        f"| Timeout 0.1 s vs 2.0 s provider | HTTP {to['status']} after {to['elapsed_s']:.3f} s | 504 shortly after 0.1 s |", "",
        "## Local sentiment sanity check", "",
        f"Accuracy {se['accuracy']:.3f} on {se['n']} sentences ({se['caveat']})", "",
        "Confusion (expected->predicted): " + ", ".join(f"`{k}`: {v}" for k, v in sorted(se["confusion"].items())), ""]
    if se["errors"]:
        lines += ["Misclassified:"] + [f"- \"{x['text']}\" expected {x['expected']}, got {x['predicted']}" for x in se["errors"]]
    return "\n".join(lines) + "\n"


async def main():
    reqs = load_requests()
    res = {
        "created_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "environment": {"platform": platform.platform(), "python": sys.version.split()[0],
                        "cpu_count": __import__("os").cpu_count()},
        "latency_throughput": await latency_and_throughput(reqs),
        "rate_limiter": rate_limit_accuracy(),
        "fallback": await fallback_success(reqs),
        "timeout": await timeout_enforcement(),
        "sentiment_sanity": sentiment_sanity(),
    }
    out = ROOT / "results"
    out.mkdir(exist_ok=True)
    (out / "results.json").write_text(json.dumps(res, indent=2))
    (out / "RESULTS.md").write_text(to_md(res))
    print(to_md(res))


if __name__ == "__main__":
    asyncio.run(main())
